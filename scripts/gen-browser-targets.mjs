// browserslist 쿼리(package.json) → Vite build.cssTarget(esbuild 타깃 문자열) 생성.
// caniuse-lite 를 먼저 갱신한 뒤 최신 통계로 산출. 결과: browser-targets.json(커밋 대상).
// 빌드·dev 는 이 파일만 참조. 재생성: pnpm update:browsers
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

// 하한 강제: browserslist 가 더 낮게 잡아도 최소 이 버전. (구형 iOS 배제 → 출력 비대화 방지)
const MIN_VERSIONS = { ios: 16.4 };

// cssTarget 이 인식하는 브라우저만(ios_saf→ios). 나머지(samsung·and_chr 등)는 제외.
const NAME_MAP = { chrome: 'chrome', edge: 'edge', firefox: 'firefox', safari: 'safari', ios_saf: 'ios', opera: 'opera', ie: 'ie' };

// 1. caniuse-lite 데이터 최신화 (브라우저 통계 갱신)
execSync('pnpm dlx update-browserslist-db@latest', { stdio: 'inherit' });

// 2. 갱신된 데이터로 browserslist 로드 (update 이후 동적 import 필수)
const browserslist = (await import('browserslist')).default;

// 3. 브라우저별 최소 버전 추출
const min = {};
for (const entry of browserslist()) {
  const [name, versions] = entry.split(' ');
  const browser = NAME_MAP[name];
  if (!browser) continue;
  const version = parseFloat(versions); // "11.0-11.2" → 11
  if (Number.isNaN(version)) continue;
  if (min[browser] === undefined || version < min[browser]) min[browser] = version;
}

// 4. 하한 적용
for (const [browser, floor] of Object.entries(MIN_VERSIONS)) {
  if (min[browser] !== undefined && min[browser] < floor) min[browser] = floor;
}

const targets = Object.entries(min)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([browser, version]) => `${browser}${version}`);

const header =
  '# Generated by `pnpm update:browsers` — do not edit by hand.\n' +
  '# CSS target browsers (minimum versions) for Lightning CSS vendor prefixing.\n';
const body = targets.map((target) => `- ${target}`).join('\n');

const out = new URL('../browser-targets.yml', import.meta.url);
writeFileSync(out, header + body + '\n');
console.log('\nbrowser-targets.yml 생성:', JSON.stringify(targets));
